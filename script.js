
const $ = id => document.getElementById(id);

let chats = JSON.parse(localStorage.getItem("studyAI_chats") || "[]");
let current = [];
let selectedImage = null;
let busy = false;

const API = "https://studyai.editorhindu96.workers.dev";

function save() {
  localStorage.setItem("studyAI_chats", JSON.stringify(chats));
  renderHistory();
}

function renderHistory() {
  $("history").innerHTML = chats.slice(-12).reverse().map((c, i) =>
    `<div class="history-item" data-i="${chats.length - 1 - i}">${escapeHTML(c.title || "New chat")}</div>`
  ).join("");

  document.querySelectorAll(".history-item").forEach(x => {
    x.onclick = () => loadChat(+x.dataset.i);
  });
}

function escapeHTML(s) {
  return String(s).replace(/[&<>"']/g, m => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;",
    '"': "&quot;", "'": "&#039;"
  }[m]));
}

function addMessage(role, text) {
  $("welcome").classList.add("hidden");

  const wrap = document.createElement("div");
  wrap.className = `message ${role}`;

  const outer = document.createElement("div");
  const label = document.createElement("div");
  label.className = "role";
  label.textContent = role === "user" ? "You" : "StudyAI";

  const bubble = document.createElement("div");
  bubble.className = "bubble";
  bubble.style.whiteSpace = "pre-wrap";
  bubble.textContent = text;

  outer.append(label, bubble);
  wrap.appendChild(outer);
  $("messages").appendChild(wrap);
  $("chat").scrollTop = $("chat").scrollHeight;
}

function addImageMessage(base64) {
  $("welcome").classList.add("hidden");

  const wrap = document.createElement("div");
  wrap.className = "message assistant";

  const outer = document.createElement("div");
  const label = document.createElement("div");
  label.className = "role";
  label.textContent = "StudyAI · Generated image";

  const bubble = document.createElement("div");
  bubble.className = "bubble";

  const img = document.createElement("img");
  img.alt = "Image generated by StudyAI";
  img.src = "data:image/jpeg;base64," + base64;
  img.style.width = "100%";
  img.style.maxWidth = "420px";
  img.style.height = "auto";
  img.style.borderRadius = "12px";
  img.style.display = "block";

  const download = document.createElement("a");
  download.textContent = "Download image";
  download.href = img.src;
  download.download = "StudyAI-image.jpg";
  download.style.display = "inline-block";
  download.style.marginTop = "10px";

  bubble.append(img, download);
  outer.append(label, bubble);
  wrap.appendChild(outer);
  $("messages").appendChild(wrap);

  $("chat").scrollTop = $("chat").scrollHeight;
}

function newChat() {
  current = [];
  selectedImage = null;
  $("messages").innerHTML = "";
  $("welcome").classList.remove("hidden");
  $("imagePreview").classList.add("hidden");
  $("prompt").value = "";
  $("imageInput").value = "";
}

function loadChat(i) {
  const c = chats[i];
  if (!c) return;

  current = c.messages || [];
  $("messages").innerHTML = "";
  $("welcome").classList.add("hidden");

  current.forEach(m => addMessage(m.role, m.text));
  $("sidebar").classList.remove("open");
}

function saveCurrentChat(title) {
  if (!current.length) return;

  chats.push({
    title: title.slice(0, 48) || "New chat",
    messages: [...current]
  });

  if (chats.length > 50) chats = chats.slice(-50);
  save();
}

async function send() {
  if (busy) return;

  const input = $("prompt");
  const raw = input.value.trim();

  if (!raw && !selectedImage) return;

  // Type /image followed by a prompt to generate an image.
  const isImage = /^\/image(?:\s|$)/i.test(raw);
  const imagePrompt = isImage ? raw.replace(/^\/image\s*/i, "").trim() : "";

  if (isImage && !imagePrompt) {
    addMessage("assistant", 'Write a prompt after /image. Example: /image a cinematic cricket champion poster');
    return;
  }

  // Photo analysis is not connected yet.
  if (selectedImage && !isImage) {
    addMessage("assistant", "Photo-based answers are not connected yet. For now, remove the photo and ask a text question, or use /image followed by a prompt to generate an image.");
    return;
  }

  const text = isImage ? imagePrompt : raw;
  const userText = isImage ? "🎨 Generate image: " + imagePrompt : text;

  addMessage("user", userText);
  current.push({ role: "user", text: userText });

  input.value = "";
  resize();

  selectedImage = null;
  $("imagePreview").classList.add("hidden");
  $("imageInput").value = "";

  busy = true;
  $("typing").classList.remove("hidden");

  try {
    const payload = isImage
      ? { mode: "image", prompt: imagePrompt }
      : {
          question: text,
          subject: "",
          class: $("classSelect").value
        };

    const response = await fetch(API, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify(payload)
    });

    const data = await response.json();

    if (!response.ok) {
      throw new Error(data.error || "Request failed");
    }

    if (isImage) {
      if (!data.image) throw new Error("No image was returned.");

      addImageMessage(data.image);
      current.push({
        role: "assistant",
        text: "[StudyAI generated an image]"
      });
    } else {
      if (!data.answer) throw new Error("No answer was returned.");

      addMessage("assistant", data.answer);
      current.push({ role: "assistant", text: data.answer });
    }

    saveCurrentChat(userText);
  } catch (error) {
    console.error("StudyAI request failed:", error);
    const msg = error.message || "Please try again.";
    addMessage("assistant", "Sorry, I couldn't complete that request. " + msg);
  } finally {
    busy = false;
    $("typing").classList.add("hidden");
    $("sendBtn").disabled = false;
  }
}

function resize() {
  const t = $("prompt");
  t.style.height = "auto";
  t.style.height = Math.min(t.scrollHeight, 130) + "px";
}

$("sendBtn").onclick = send;

$("prompt").addEventListener("input", resize);

$("prompt").addEventListener("keydown", e => {
  if (e.key === "Enter" && !e.shiftKey) {
    e.preventDefault();
    send();
  }
});

$("newChat").onclick = newChat;
$("menuBtn").onclick = () => $("sidebar").classList.toggle("open");

$("themeBtn").onclick = () => {
  document.body.classList.toggle("dark");
  localStorage.setItem(
    "studyAI_dark",
    document.body.classList.contains("dark")
  );
};

$("clearBtn").onclick = () => {
  if (confirm("Clear saved chats?")) {
    chats = [];
    save();
    newChat();
  }
};

if (localStorage.getItem("studyAI_dark") === "true") {
  document.body.classList.add("dark");
}

$("imageBtn").onclick = () => $("imageInput").click();

$("imageInput").onchange = e => {
  const file = e.target.files[0];
  if (!file) return;

  if (!file.type.startsWith("image/")) {
    alert("Please choose an image file.");
    e.target.value = "";
    return;
  }

  selectedImage = file;
  $("previewImg").src = URL.createObjectURL(file);
  $("imagePreview").classList.remove("hidden");
};

$("removeImage").onclick = () => {
  selectedImage = null;
  $("imageInput").value = "";
  $("imagePreview").classList.add("hidden");
};

document.querySelectorAll(".chip").forEach(b => {
  b.onclick = () => {
    $("prompt").value = b.dataset.prompt;
    resize();
    $("prompt").focus();
  };
});

document.querySelectorAll(".side-btn[data-subject]").forEach(b => {
  b.onclick = () => {
    $("prompt").value =
      `Help me with my ${b.dataset.subject} homework. Explain the answer step by step.`;
    resize();
    $("prompt").focus();
    $("sidebar").classList.remove("open");
  };
});

